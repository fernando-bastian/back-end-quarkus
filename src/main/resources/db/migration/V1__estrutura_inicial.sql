CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL CHECK (length(trim(nome)) > 0),
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL
);

CREATE TABLE contas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    nome VARCHAR(100) NOT NULL CHECK (length(trim(nome)) > 0),
    UNIQUE (id, usuario_id)
);
CREATE INDEX idx_contas_usuario ON contas(usuario_id);

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    nome VARCHAR(100) NOT NULL CHECK (length(trim(nome)) > 0),
    UNIQUE (id, usuario_id)
);
CREATE INDEX idx_categorias_usuario ON categorias(usuario_id);

CREATE TABLE transacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    conta_id BIGINT NOT NULL,
    categoria_id BIGINT,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('RECEITA', 'DESPESA', 'TRANSFERENCIA_SAIDA', 'TRANSFERENCIA_ENTRADA')),
    valor NUMERIC(19,2) NOT NULL CHECK (valor > 0),
    data DATE NOT NULL,
    descricao VARCHAR(255),
    transferencia_id UUID,
    FOREIGN KEY (conta_id, usuario_id) REFERENCES contas(id, usuario_id),
    FOREIGN KEY (categoria_id, usuario_id) REFERENCES categorias(id, usuario_id),
    CHECK (
        (tipo IN ('RECEITA', 'DESPESA') AND categoria_id IS NOT NULL AND transferencia_id IS NULL)
        OR (tipo IN ('TRANSFERENCIA_SAIDA', 'TRANSFERENCIA_ENTRADA') AND categoria_id IS NULL AND transferencia_id IS NOT NULL)
    ),
    UNIQUE (transferencia_id, tipo)
);
CREATE INDEX idx_transacoes_usuario_conta_categoria ON transacoes(usuario_id, conta_id, categoria_id);
CREATE INDEX idx_transacoes_usuario_categoria ON transacoes(usuario_id, categoria_id);
